"use client";

import React, { useState, useEffect, useRef } from "react";
import type { Node as ProseMirrorNode } from "@tiptap/pm/model";
import { useEditor, EditorContent } from "@tiptap/react";
import StarterKit from "@tiptap/starter-kit";
import Placeholder from "@tiptap/extension-placeholder";
import TaskList from "@tiptap/extension-task-list";
import TaskItem from "@tiptap/extension-task-item";
import { Markdown } from "tiptap-markdown";
import { sanitizeCorruptedContent } from "@/lib/storage";
import { AskAIPanel } from "@/components/editor/AskAIPanel";
import { WriteWithAIPanel } from "@/components/editor/WriteWithAIPanel";
import {
  Bold,
  Italic,
  Code,
  Heading1,
  Heading2,
  Heading3,
  List,
  ListOrdered,
  CheckSquare,
  Quote,
  Sparkles,
  Wand2,
  ChevronUp,
} from "lucide-react";

interface NexusEditorProps {
  noteId: string;
  initialContent: string;
  noteTitle: string;
  onUpdateTitle: (newTitle: string) => void;
  onUpdateContent: (content: string) => void;
  currentUserId?: string;
  onOpenAISettings?: () => void;
}

interface MarkdownSerializerStateLike {
  write: (text: string) => void;
  renderContent: (node: ProseMirrorNode) => void;
}

const CustomTaskItem = TaskItem.extend({
  addStorage() {
    return {
      markdown: {
        serialize(state: MarkdownSerializerStateLike, node: ProseMirrorNode) {
          const check = node.attrs.checked ? "[x]" : "[ ]";
          state.write(`${check} `);
          state.renderContent(node);
        },
        parse: {
          updateDOM(element: HTMLElement) {
            // 1. Process standard task-list items generated by markdown-it-task-lists
            element.querySelectorAll<HTMLElement>(".task-list-item").forEach((item) => {
              const input = item.querySelector<HTMLInputElement>("input");
              item.setAttribute("data-type", "taskItem");
              if (input) {
                item.setAttribute("data-checked", input.checked ? "true" : "false");
                input.remove();
              }
            });

            // 2. Process empty or unhandled task items (e.g. "- [ ]" without trailing space)
            element.querySelectorAll<HTMLElement>("li").forEach((li) => {
              if (li.getAttribute("data-type") === "taskItem") return;
              const text = li.textContent?.trim() || "";
              const match = text.match(/^\[([ xX])\](?:\s*(.*))?$/);
              if (match) {
                li.setAttribute("data-type", "taskItem");
                li.setAttribute("data-checked", match[1].toLowerCase() === "x" ? "true" : "false");
                const remainingText = match[2] || "";
                li.innerHTML = `<p>${remainingText}</p>`;
              }
            });

            // 3. Mark any parent <ul> that contains a taskItem
            element.querySelectorAll<HTMLElement>('li[data-type="taskItem"]').forEach((li) => {
              const parent = li.parentElement;
              if (parent && parent.tagName === "UL") {
                parent.setAttribute("data-type", "taskList");
              }
            });
          },
        },
      },
    };
  },
});

const EDITOR_EXTENSIONS = [
  StarterKit.configure({
    heading: {
      levels: [1, 2, 3],
    },
    link: {
      openOnClick: false,
      HTMLAttributes: {
        class: "text-sky-400 hover:text-sky-300 underline underline-offset-2",
      },
    },
  }),
  Placeholder.configure({
    placeholder: "Write thoughts, record insights, or organize concepts...",
  }),
  TaskList,
  CustomTaskItem.configure({
    nested: true,
  }),
  Markdown.configure({
    html: false,
    tightLists: true,
    bulletListMarker: "-",
    linkify: true,
    breaks: true,
  }),
];

const EDITOR_PROPS = {
  attributes: {
    class:
      "nexus-editor-content focus:outline-none min-h-[200px] sm:min-h-[380px] text-gray-200 text-base sm:text-[17px] leading-relaxed",
  },
};

export const NexusEditor: React.FC<NexusEditorProps> = ({
  noteId,
  initialContent,
  noteTitle,
  onUpdateTitle,
  onUpdateContent,
  currentUserId,
  onOpenAISettings,
}) => {
  const lastEmittedMarkdownRef = useRef<string>(sanitizeCorruptedContent(initialContent));
  const currentNoteIdRef = useRef<string>(noteId);
  const [activeAIPanel, setActiveAIPanel] = useState<"ask" | "write" | null>(null);
  const [isAIMenuOpen, setIsAIMenuOpen] = useState(false);
  const aiMenuRef = useRef<HTMLDivElement | null>(null);

  // Close floating AI menu when clicking outside or pressing Escape
  useEffect(() => {
    if (!isAIMenuOpen) return;

    const handleClickOutside = (e: MouseEvent) => {
      if (aiMenuRef.current && !aiMenuRef.current.contains(e.target as Node)) {
        setIsAIMenuOpen(false);
      }
    };

    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === "Escape") {
        setIsAIMenuOpen(false);
      }
    };

    document.addEventListener("mousedown", handleClickOutside);
    window.addEventListener("keydown", handleKeyDown);
    return () => {
      document.removeEventListener("mousedown", handleClickOutside);
      window.removeEventListener("keydown", handleKeyDown);
    };
  }, [isAIMenuOpen]);

  const editor = useEditor({
    extensions: EDITOR_EXTENSIONS,
    content: sanitizeCorruptedContent(initialContent),
    immediatelyRender: false,
    shouldRerenderOnTransaction: true,
    editorProps: EDITOR_PROPS,
    onUpdate: ({ editor }) => {
      const storage = editor.storage as unknown as {
        markdown?: { getMarkdown: () => string };
      };
      const md = storage.markdown?.getMarkdown() ?? "";
      lastEmittedMarkdownRef.current = md;
      onUpdateContent(md);
    },
  });

  // Sync editor content if note switches or changes externally
  useEffect(() => {
    if (!editor) return;

    const sanitized = sanitizeCorruptedContent(initialContent);

    if (currentNoteIdRef.current !== noteId) {
      currentNoteIdRef.current = noteId;
      lastEmittedMarkdownRef.current = sanitized;
      editor.commands.setContent(sanitized, { emitUpdate: false });
      return;
    }

    const storage = editor.storage as unknown as {
      markdown?: { getMarkdown: () => string };
    };
    const currentMd = storage.markdown?.getMarkdown() ?? "";

    if (sanitized !== lastEmittedMarkdownRef.current && sanitized !== currentMd) {
      lastEmittedMarkdownRef.current = sanitized;
      editor.commands.setContent(sanitized, { emitUpdate: false });
    }
  }, [noteId, initialContent, editor]);

  if (!editor) {
    return (
      <div className="flex-1 flex items-center justify-center text-gray-400 text-base">
        Loading editor...
      </div>
    );
  }

  // Calculate statistics
  const text = editor.getText();
  const wordCount = text.trim() ? text.trim().split(/\s+/).length : 0;
  const readingTime = Math.ceil(wordCount / 200);

  const handleApproveDraft = (draftMarkdown: string) => {
    const trimmed = draftMarkdown.trim();
    if (!trimmed) return;

    const currentDocText = editor.getText().trim();
    if (!currentDocText) {
      editor.commands.setContent(trimmed);
    } else {
      // Focus and insert at cursor, or append to end
      editor.chain().focus().insertContent(`\n\n${trimmed}\n`).run();
    }

    const storage = editor.storage as unknown as {
      markdown?: { getMarkdown: () => string };
    };
    const md = storage.markdown?.getMarkdown() ?? "";
    lastEmittedMarkdownRef.current = md;
    onUpdateContent(md);

    setActiveAIPanel(null);
  };

  return (
    <div className="flex-1 flex flex-col min-h-0 h-full w-full bg-[#06080F] text-slate-100 overflow-hidden relative">
      {/* 1. Main Editable Canvas (Title and Body now clean at the top) */}
      <div className="flex-1 min-h-0 overflow-y-auto custom-scrollbar pb-24 md:pb-8">
        <div className="max-w-4xl mx-auto px-5 sm:px-10 py-7 sm:py-10">
          {/* Main Canonical Title Input */}
          <div className="mb-6 sm:mb-8">
            <input
              type="text"
              value={noteTitle}
              onChange={(e) => onUpdateTitle(e.target.value)}
              placeholder="Untitled Note"
              className="w-full text-3xl sm:text-4xl md:text-5xl font-extrabold bg-transparent text-white border-none focus:outline-none placeholder-slate-600 tracking-tight"
            />
          </div>

          <EditorContent editor={editor} />
        </div>
      </div>

      {/* Floating AI Panels */}
      {activeAIPanel === "ask" && (
        <AskAIPanel
          key={noteId}
          noteId={noteId}
          noteTitle={noteTitle}
          getCurrentContent={() => lastEmittedMarkdownRef.current}
          currentUserId={currentUserId}
          onClose={() => setActiveAIPanel(null)}
          onOpenSettings={onOpenAISettings}
        />
      )}

      {activeAIPanel === "write" && (
        <WriteWithAIPanel
          noteTitle={noteTitle}
          getCurrentContent={() => lastEmittedMarkdownRef.current}
          currentUserId={currentUserId}
          onApprove={handleApproveDraft}
          onDecline={() => setActiveAIPanel(null)}
          onOpenSettings={onOpenAISettings}
        />
      )}

      {/* 2. Formatting Toolbar Docked at the Bottom */}
      <div className="fixed bottom-0 inset-x-0 md:static shrink-0 z-20 px-3 sm:px-8 pt-2.5 pb-[max(0.75rem,env(safe-area-inset-bottom))] bg-[#0E1525]/95 backdrop-blur-md border-t border-slate-700/90 shadow-[0_-8px_24px_rgba(0,0,0,0.65)] flex items-center justify-between gap-3 text-slate-200">
        <div className="flex items-center gap-1 sm:gap-1.5 min-w-0 flex-1">
          {/* Unified AI Button with Floating Options Menu */}
          <div className="relative shrink-0" ref={aiMenuRef}>
            <button
              type="button"
              onMouseDown={(e) => e.preventDefault()}
              onClick={() => setIsAIMenuOpen((prev) => !prev)}
              className={`flex items-center gap-1.5 px-2.5 sm:px-3 py-2 rounded-lg text-xs sm:text-sm font-semibold transition shrink-0 touch-manipulation ${
                isAIMenuOpen || activeAIPanel !== null
                  ? "text-sky-200 bg-sky-950/90 border border-sky-600/80 shadow-xs shadow-sky-950/50"
                  : "text-sky-300 hover:text-white hover:bg-slate-800/90 bg-sky-950/30 border border-sky-800/40"
              }`}
              title="AI Tools"
            >
              <Sparkles className="w-4 h-4 text-sky-400" />
              <span>AI</span>
              <ChevronUp
                className={`w-3.5 h-3.5 transition-transform duration-200 ${
                  isAIMenuOpen ? "rotate-180 text-sky-300" : "text-slate-400"
                }`}
              />
            </button>

            {/* Floating Options Menu */}
            {isAIMenuOpen && (
              <div className="absolute bottom-full left-0 mb-2.5 z-40 w-56 sm:w-60 p-1.5 bg-[#0B0F19]/95 backdrop-blur-xl border border-slate-700/80 rounded-xl shadow-[0_12px_36px_rgba(0,0,0,0.85)] flex flex-col gap-1 text-slate-200 animate-in fade-in slide-in-from-bottom-2 duration-150">
                <button
                  type="button"
                  onClick={() => {
                    setActiveAIPanel((prev) => (prev === "ask" ? null : "ask"));
                    setIsAIMenuOpen(false);
                  }}
                  className={`w-full flex items-center gap-2.5 px-3 py-2 rounded-lg text-xs sm:text-sm font-medium transition text-left ${
                    activeAIPanel === "ask"
                      ? "bg-sky-950/80 text-sky-200 border border-sky-800/60"
                      : "hover:bg-[#162032] hover:text-white text-slate-200"
                  }`}
                >
                  <div className="w-7 h-7 rounded-lg bg-sky-950/80 border border-sky-700/60 flex items-center justify-center shrink-0">
                    <Sparkles className="w-4 h-4 text-sky-400" />
                  </div>
                  <div className="min-w-0">
                    <div className="font-semibold text-slate-100 flex items-center gap-1.5">
                      <span>Ask AI</span>
                      {activeAIPanel === "ask" && (
                        <span className="text-[10px] px-1.5 py-0.2 rounded bg-sky-900/60 text-sky-300">
                          Active
                        </span>
                      )}
                    </div>
                    <div className="text-[11px] text-slate-400 truncate">
                      Ask questions about this note
                    </div>
                  </div>
                </button>

                <button
                  type="button"
                  onClick={() => {
                    setActiveAIPanel((prev) => (prev === "write" ? null : "write"));
                    setIsAIMenuOpen(false);
                  }}
                  className={`w-full flex items-center gap-2.5 px-3 py-2 rounded-lg text-xs sm:text-sm font-medium transition text-left ${
                    activeAIPanel === "write"
                      ? "bg-indigo-950/80 text-indigo-200 border border-indigo-800/60"
                      : "hover:bg-[#162032] hover:text-white text-slate-200"
                  }`}
                >
                  <div className="w-7 h-7 rounded-lg bg-indigo-950/80 border border-indigo-700/60 flex items-center justify-center shrink-0">
                    <Wand2 className="w-4 h-4 text-indigo-400" />
                  </div>
                  <div className="min-w-0">
                    <div className="font-semibold text-slate-100 flex items-center gap-1.5">
                      <span>Write with AI</span>
                      {activeAIPanel === "write" && (
                        <span className="text-[10px] px-1.5 py-0.2 rounded bg-indigo-900/60 text-indigo-300">
                          Active
                        </span>
                      )}
                    </div>
                    <div className="text-[11px] text-slate-400 truncate">
                      Draft, outline, or expand text
                    </div>
                  </div>
                </button>
              </div>
            )}
          </div>

          <div className="w-[1px] h-5 bg-slate-700 mx-1 shrink-0" />

          <div className="flex items-center gap-1 sm:gap-1.5 overflow-x-auto no-scrollbar py-0.5">

          <button
            type="button"
            onMouseDown={(e) => e.preventDefault()}
            onClick={() => editor.chain().focus().toggleHeading({ level: 1 }).run()}
            className={`p-2.5 sm:p-2 rounded-lg hover:bg-slate-800 hover:text-white transition shrink-0 touch-manipulation ${
              editor.isActive("heading", { level: 1 })
                ? "text-sky-300 bg-sky-950/80 border border-sky-700/60 shadow-xs"
                : "text-slate-200"
            }`}
            title="Heading 1"
          >
            <Heading1 className="w-5 h-5" />
          </button>
          <button
            type="button"
            onMouseDown={(e) => e.preventDefault()}
            onClick={() => editor.chain().focus().toggleHeading({ level: 2 }).run()}
            className={`p-2.5 sm:p-2 rounded-lg hover:bg-slate-800 hover:text-white transition shrink-0 touch-manipulation ${
              editor.isActive("heading", { level: 2 })
                ? "text-sky-300 bg-sky-950/80 border border-sky-700/60 shadow-xs"
                : "text-slate-200"
            }`}
            title="Heading 2"
          >
            <Heading2 className="w-5 h-5" />
          </button>
          <button
            type="button"
            onMouseDown={(e) => e.preventDefault()}
            onClick={() => editor.chain().focus().toggleHeading({ level: 3 }).run()}
            className={`p-2.5 sm:p-2 rounded-lg hover:bg-slate-800 hover:text-white transition shrink-0 touch-manipulation ${
              editor.isActive("heading", { level: 3 })
                ? "text-sky-300 bg-sky-950/80 border border-sky-700/60 shadow-xs"
                : "text-slate-200"
            }`}
            title="Heading 3"
          >
            <Heading3 className="w-5 h-5" />
          </button>

          <div className="w-[1px] h-5 bg-slate-700 mx-1 shrink-0" />

          <button
            type="button"
            onMouseDown={(e) => e.preventDefault()}
            onClick={() => editor.chain().focus().toggleBold().run()}
            className={`p-2.5 sm:p-2 rounded-lg hover:bg-slate-800 hover:text-white transition shrink-0 touch-manipulation ${
              editor.isActive("bold")
                ? "text-sky-300 bg-sky-950/80 border border-sky-700/60 shadow-xs"
                : "text-slate-200"
            }`}
            title="Bold"
          >
            <Bold className="w-5 h-5" />
          </button>
          <button
            type="button"
            onMouseDown={(e) => e.preventDefault()}
            onClick={() => editor.chain().focus().toggleItalic().run()}
            className={`p-2.5 sm:p-2 rounded-lg hover:bg-slate-800 hover:text-white transition shrink-0 touch-manipulation ${
              editor.isActive("italic")
                ? "text-sky-300 bg-sky-950/80 border border-sky-700/60 shadow-xs"
                : "text-slate-200"
            }`}
            title="Italic"
          >
            <Italic className="w-5 h-5" />
          </button>
          <button
            type="button"
            onMouseDown={(e) => e.preventDefault()}
            onClick={() => editor.chain().focus().toggleCode().run()}
            className={`p-2.5 sm:p-2 rounded-lg hover:bg-slate-800 hover:text-white transition shrink-0 touch-manipulation ${
              editor.isActive("code")
                ? "text-sky-300 bg-sky-950/80 border border-sky-700/60 shadow-xs"
                : "text-slate-200"
            }`}
            title="Inline Code"
          >
            <Code className="w-5 h-5" />
          </button>

          <div className="w-[1px] h-5 bg-slate-700 mx-1 shrink-0" />

          <button
            type="button"
            onMouseDown={(e) => e.preventDefault()}
            onClick={() => editor.chain().focus().toggleBulletList().run()}
            className={`p-2.5 sm:p-2 rounded-lg hover:bg-slate-800 hover:text-white transition shrink-0 touch-manipulation ${
              editor.isActive("bulletList")
                ? "text-sky-300 bg-sky-950/80 border border-sky-700/60 shadow-xs"
                : "text-slate-200"
            }`}
            title="Bullet List"
          >
            <List className="w-5 h-5" />
          </button>
          <button
            type="button"
            onMouseDown={(e) => e.preventDefault()}
            onClick={() => editor.chain().focus().toggleOrderedList().run()}
            className={`p-2.5 sm:p-2 rounded-lg hover:bg-slate-800 hover:text-white transition shrink-0 touch-manipulation ${
              editor.isActive("orderedList")
                ? "text-sky-300 bg-sky-950/80 border border-sky-700/60 shadow-xs"
                : "text-slate-200"
            }`}
            title="Numbered List"
          >
            <ListOrdered className="w-5 h-5" />
          </button>
          <button
            type="button"
            onMouseDown={(e) => e.preventDefault()}
            onClick={() => editor.chain().focus().toggleTaskList().run()}
            className={`p-2.5 sm:p-2 rounded-lg hover:bg-slate-800 hover:text-white transition shrink-0 touch-manipulation ${
              editor.isActive("taskList")
                ? "text-sky-300 bg-sky-950/80 border border-sky-700/60 shadow-xs"
                : "text-slate-200"
            }`}
            title="Task Checklist"
          >
            <CheckSquare className="w-5 h-5" />
          </button>
          <button
            type="button"
            onMouseDown={(e) => e.preventDefault()}
            onClick={() => editor.chain().focus().toggleBlockquote().run()}
            className={`p-2.5 sm:p-2 rounded-lg hover:bg-slate-800 hover:text-white transition shrink-0 touch-manipulation ${
              editor.isActive("blockquote")
                ? "text-sky-300 bg-sky-950/80 border border-sky-700/60 shadow-xs"
                : "text-slate-200"
            }`}
            title="Blockquote"
          >
            <Quote className="w-5 h-5" />
          </button>
        </div>
      </div>

        {/* Word Count & Read Time Summary */}
        <div className="hidden sm:flex items-center gap-2 text-xs sm:text-sm text-slate-300 shrink-0 font-medium pl-3 border-l border-slate-700">
          <span>{wordCount} words</span>
          <span>·</span>
          <span>~{readingTime} min read</span>
        </div>
      </div>
    </div>
  );
};
